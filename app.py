M_DB = {"1": ("Сентябрь", 45), "2": ("Январь", 25), "3": ("Май", 5)}

def main():
	print("=" * 85)
	print("👑 ИИ-КОНСАЛТИНГ «ЕГЭ-НАВИГАТОР PRESTIGE» v39.0 👑")
	print("=" * 85)

	print("\n🌍 ВЫБЕРИ ЖЕЛАЕМЫЙ РЕГИОН ОБУЧЕНИЯ:")
	for k, v in REGIONS_DB.items(): print(f"  {k}. {v}")
	target_reg_key = input("Введи номер приоритетного региона (1-10): ").strip()
	target_reg_name = REGIONS_DB[target_reg_key]

	print("\n📅 МЕСЯЦ ЗАМЕРА:")
	for k, v in M_DB.items(): print(f"  {k}. {v}")
	m_key = input("1. Выбери месяц замера (1-3): ").strip()
	sel_m_name, m_potential = M_DB[m_key]
	
	curr_s = int(input("2. Твои текущие баллы на пробниках: "))
	target_s = int(input("3. Желаемая сумма баллов на ЕГЭ: "))
	need_d = input("4. Требуется общежитие? (да/нет): ").strip().lower() == "да"
	
	print("\nНАПРАВЛЕНИЯ:") 
	for k, v in DIRS.items(): print(f"  {k}. {v}")
	d_key = input("5. Выбери номер направления (1-10): ").strip()
	sel_d_name, d_mod, bvi_p, pr_m, sl_m, infl = DIRS[d_key]
	
	print("\nДОСТИЖЕНИЯ:\n  1. Медаль\n  2. ГТО\n  3. Нет")
	id_c = input("6. Выбери пункт (1-3): ").strip()
	bonus = 5 if id_c == "1" else 2 if id_c == "2" else 0
	
	print("\nИНТЕНСИВНОСТЬ:\n  1. Высокая\n  2. Средняя\n  3. Низкая")
	eff = 1.15 if input("7. Выбери пункт (1-3): ").strip() == "1" else 0.95
	
	comm_ok = input("8. Рассматриваете ли платку? (да/нет): ").strip().lower() == "да"
	olymp_ok = input("9. Пишете олимпиады для БВИ? (да/нет): ").strip().lower() == "да"
	tech_ok = input("10. Сдаете Проф. Математику/Информатику? (да/нет): ").strip().lower() == "да"
	move_ok = input("11. Рассматривать ли другие регионы как запасные? (да/нет): ").strip().lower() == "да"
	
	print("\nЦЕЛЬ:\n  1. Высокий доход\n  2. Наука\n  3. Стартап")
	goal_c = input("12. Выбери цель (1-3): ").strip()
	
	print("\nБЮДЖЕТ ПЛАТКИ:\n  1. До 150к\n  2. До 300к\n  3. Свыше 300к")
	bud_c = input("13. Выбери лимит (1-3): ").strip()
	
	mil_ok = input("14. Нужен ли Военный учебный центр? (да/нет): ").strip().lower() == "да"
	brand_ok = input("15. В приоритете престиж вуза? (да/нет): ").strip().lower() == "да"
	lang_ok = input("16. Высокий уровень ин. языка? (да/нет): ").strip().lower() == "да"
	work_ok = input("17. Планируешь работать на 1-2 курсе? (да/нет): ").strip().lower() == "да"
	vol_ok = input("18. Есть официальная волонтерская книжка? (да/нет): ").strip().lower() == "да"
	brand_mind = input("19. У тебя аналитический склад ума? (да/нет): ").strip().lower() == "да"

	max_p = min(curr_s + round(m_potential * eff) + bonus + (2 if vol_ok else 0), 310)
	
	primary_pool = []
	backup_pool = []

	for vuz_name, params in VUZ_REGISTRY.items():
		vuz_base, price_mult, sal_mult, bvi_mult, dorm_risk, r_tag = params
		
		vuz_b = vuz_base + d_mod
		if tech_ok and d_key in ["1", "2", "6"]: vuz_b += 3
		if brand_mind and d_key in ["1", "2"]: vuz_b += 1
		
		fc27 = round(vuz_b + 4.5 + infl)
		bvi_s = min(0.45 * bvi_mult * bvi_p * (0.4 if olymp_ok else 1.0), 0.95)
		
		reg_price = 420000 if r_tag == "1" else 340000 if r_tag == "2" else 230000
		reg_sal = 110000 if r_tag == "1" else 90000 if r_tag == "2" else 65000
		
		price = round(reg_price * price_mult * pr_m)
		if bud_c == "1" and price > 150000 and not comm_ok: continue
		if bud_c == "2" and price > 300000 and not comm_ok: continue

		sal = round(reg_sal * sal_mult * sl_m * (1.4 if goal_c == "3" else 1.0))
		if lang_ok and d_key in ["2", "9"]: sal = round(sal * 1.2)
		if work_ok: sal = round(sal * 1.15)
		
		roi = round((price * 4) / sal) if sal > 0 else 0
		dorm = min(max(round((1 - dorm_risk * (1.1 if need_d else 0.6)) * 100), 0), 100)

		match_score = 100 - abs(target_s - fc27)

		res = {
			"name": vuz_name, "reg_name": REGIONS_DB[r_tag], "fc": fc27, "bvi": round(bvi_s*100), 
			"pr": price, "sal": sal, "roi": roi, "dr": dorm, "ms": match_score
		}
		
		if r_tag == target_reg_key:
			primary_pool.append(res)
		elif move_ok:
			backup_pool.append(res)

	primary_pool.sort(key=lambda x: x["ms"], reverse=True)
	backup_pool.sort(key=lambda x: x["ms"], reverse=True)

	final_vuz_list = []
	for v in primary_pool:
		if len(final_vuz_list) < 10: final_vuz_list.append((v, "🟢 ЦЕЛЕВОЙ РЕГИОН"))
	for v in backup_pool:
		if len(final_vuz_list) < 10: final_vuz_list.append((v, "🔵 ЗАПАСНОЙ ВАРИАНТ"))

	print("\n" + "👑 " * 20)
	print("📋 ИТОГОВЫЙ СКОРИНГ: СТРАТЕГИЧЕСКИЙ ОТЧЕТ ИЗ 10 ЛУЧШИХ КОНКРЕТНЫХ ВУЗОВ")
	print(f"📖 Направление: {sel_d_name}")
	print(f"📐 Твоя цель: {target_s} б. | Предиктивный потенциал к лету 2027: {max_p} б.")
	print("-" * 80)

	if not final_vuz_list:
		print("   По выбранным фильтрам и бюджетам подходящих вузов в РФ не найдено.")
	else:
		for idx, (item, status_tag) in enumerate(final_vuz_list, 1):
			print(f"   {idx}. {status_tag} | {item['name']} ({item['reg_name']})")
			print(f"      🔮 Прогноз порога на бюджет 2027: {item['fc']} б. | БВИ (Олимпиады): {item['bvi']}% мест")
			if need_d: print(f"      🛌 Шанс получить общежитие: {item['dr']}%")
			if comm_ok: print(f"      💳 Коммерция: {item['pr']} руб./год | Прогноз ЗП: ~{item['sal']} руб./мес. | ROI: {item['roi']} мес.")
			print("      " + "."*45)

	print("\n🧠 ШАГ 4. ПЕРСОНАЛЬНЫЕ СТРАТЕГИЧЕСКИЕ РЕКОМЕНДАЦИИ:")
	print(f"   1. [Тайминг замера]: Сейчас {sel_m_name}. Твой потенциал прироста баллов: +{max_p - curr_s} б.")
	if max_p < target_s:
		print("      ⚠️ Твоя цель завышена относительно текущего темпа. Срочно смени формат подготовки на репетиторов.")
	else:
		print("      💪 Твой математический потенциал полностью покрывает выбранные цели. Удерживай планку.")
		
	avg_bvi = sum(v["bvi"] for v, _ in final_vuz_list) / len(final_vuz_list) if final_vuz_list else 0
	if avg_bvi >= 55:
		print("   2. [Олимпиадная угроза]: В пуле выбранных вузов зафиксировано экстремальное давление БВИ.")
		print("      🔥 СОВЕТ: Поступление строго по ЕГЭ рискованно. Срочно зарегистрируйся на олимпиады из перечня РСОШ.")
	else:
		print("   2. [Конкурсный трек]: Олимпиадное давление умеренное, делай упор на качественную сдачу ЕГЭ.")
		
	if need_d and final_vuz_list and any(v["dr"] < 40 for v, _ in final_vuz_list):
		print("   3. [Жилищные риски]: Вероятность заселения в бесплатный кампус в ряде выбранных вузов низкая.")
		print("      💡 СОВЕТ: Заранее заложи в семейный бюджет расходы на долгосрочный наем коммерческого жилья.")

	print("👑 " * 20)

if __name__ == '__main__': main()
